public class CoalGeneratorBlock extends BaseEntityBlock {
    public CoalGeneratorBlock(Properties properties) {
        super(properties);
    }

    /* BLOCK ENTITY */
    @Override
    public @Nullable BlockEntity newBlockEntity(BlockPos worldPosition, BlockState blockState) {
        return new CoalGeneratorBlockEntity(worldPosition, blockState);
    }

    @Override
    public boolean onDestroyedByPlayer(BlockState state, Level level, BlockPos pos, Player player, ItemStack toolStack, boolean willHarvest, FluidState fluid) {
        BlockEntity blockEntity = level.getBlockEntity(pos);
        if (blockEntity instanceof CoalGeneratorBlockEntity coalGeneratorBlockEntity) {
            coalGeneratorBlockEntity.drops();
        }
        return super.onDestroyedByPlayer(state, level, pos, player, toolStack, willHarvest, fluid);
    }

    @Override
    protected InteractionResult useWithoutItem(BlockState state, Level level, BlockPos pos, Player player, BlockHitResult hitResult) {
        if (!level.isClientSide()) {
            BlockEntity entity = level.getBlockEntity(pos);
            if(entity instanceof CoalGeneratorBlockEntity coalGeneratorBlockEntity) {
                player.openMenu(new SimpleMenuProvider(coalGeneratorBlockEntity, Component.translatable("block.mccourse.coal_generator")), pos);
            } else {
                throw new IllegalStateException("Our Container provider is missing!");
            }
        }
        return InteractionResult.SUCCESS;
    }

    @Override
    public @Nullable <T extends BlockEntity> BlockEntityTicker<T> getTicker(Level level, BlockState blockState, BlockEntityType<T> type) {
        if(level.isClientSide()) {
            return null;
        }

        return createTickerHelper(type, ModBlockEntities.COAL_GENERATOR_BE.get(), (level1, pos, state, entity) ->
                entity.tick(level1, pos, state));
    }
}
